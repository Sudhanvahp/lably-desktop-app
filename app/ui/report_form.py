    @staticmethod
    def _set_date(field: QDateTimeEdit, text: str):
        """Put a stored date string back into a picker.

        Reports saved before the pickers existed hold whatever was typed, so an
        unreadable value falls back to now rather than throwing."""
        parsed = QDateTime.fromString(text or "", QT_DATE_FMT)
        if not parsed.isValid():
            parsed = QDateTime.fromString(text or "", "dd-MM-yyyy hh:mm AP")
        field.setDateTime(parsed if parsed.isValid() else QDateTime.currentDateTime())

    @staticmethod
    def _date_field() -> QDateTimeEdit:
        field = QDateTimeEdit()
        field.setDisplayFormat("dd-MM-yyyy  hh:mm AP")
        field.setCalendarPopup(True)
        field.setDateTime(QDateTime.currentDateTime())
        field.setMinimumDate(QDate(1900, 1, 1))
        field.setMaximumDateTime(QDateTime.currentDateTime().addYears(1))
        return field

    @staticmethod
    def _label(text: str) -> QLabel:
        label = QLabel(text)
        label.setObjectName("FieldLabel")
        return label

