    def _build_bill_totals(self) -> QFrame:
        """Total / payable / deposit / balance, stacked under the amount column.

        The deposit is the only editable line, so it sits in the same column as
        the figures it is subtracted from rather than off in a form of its own.
        """
        frame = QFrame()
        frame.setObjectName("BillTotals")
        grid = QGridLayout(frame)
        grid.setContentsMargins(S3, S2 + 2, S3, S2 + 2)
        grid.setHorizontalSpacing(S3)
        grid.setVerticalSpacing(6)

        def caption(text: str, row: int, name: str = "BillLabel"):
            label = QLabel(text)
            label.setObjectName(name)
            label.setAlignment(Qt.AlignRight | Qt.AlignVCenter)
            grid.addWidget(label, row, 0)

        def figure(row: int, name: str = "BillValue") -> QLabel:
            label = QLabel(billing.format_amount(0))
            label.setObjectName(name)
            label.setAlignment(Qt.AlignRight | Qt.AlignVCenter)
            label.setMinimumWidth(130)
            grid.addWidget(label, row, 1)
            return label

        caption("Total Billed", 0)
        self.l_total = figure(0)
        caption("Net Payable", 1)
        self.l_payable = figure(1)

        caption("Net Deposit", 2)
        self.f_deposit = self._amount_field()
        self.f_deposit.textChanged.connect(self._update_bill_totals)
        # The sign sits outside the box: inside it, the operator has to type
        # around it, and the amount validator would reject it anyway.
