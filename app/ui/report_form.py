    def print_bill(self):
        """Save before printing, for the same reason the report does: a bill
        handed to a patient must exist in the history, with its number."""
        if not self._bill_ready():
            return
        if not self.read_only and not self.save():
            return
        if printing.print_report(self._bill_html(), self, "Print Bill",
                                printing.BILL_PAGE):
            self.notify.emit(
                f"Bill {self.f_bill_no.text()} sent to the printer.", "success")
        else:
            self.notify.emit("Printing cancelled.", "warning")

