    # ------------------------------------------------------------ read-only
    def set_read_only(self, locked: bool, message: str = ""):
        """A saved report opens locked: it is a medical record that has already
        been printed and handed over, so changing it should be deliberate."""
        self.read_only = locked
        self.lock_bar.setVisible(locked)
        if message:
            self.lock_message.setText(message)
        self.header.title.setText("Saved Report" if locked else "New Report")
        self.print_button.setText("Print" if locked else "Save and Print")

        for widget in (self.f_name, self.f_age, self.f_phone, self.f_ref,
                       self.f_remarks, self.f_bill_no, self.f_billed_by,
                       self.f_deposit):
            widget.setReadOnly(locked)
        for widget in (self.f_collected, self.f_reported, self.f_bill_date):
            widget.setReadOnly(locked)
            widget.setCalendarPopup(not locked)
        for widget in (self.f_age_unit, self.f_sex, self.f_sample,
                       self.f_bill_type):
            widget.setEnabled(not locked)
        for cb in self.panel_boxes.values():
            cb.setEnabled(not locked)

        triggers = (QAbstractItemView.NoEditTriggers if locked
                    else QAbstractItemView.DoubleClicked
                    | QAbstractItemView.EditKeyPressed
                    | QAbstractItemView.AnyKeyPressed)
        self.table.setEditTriggers(triggers)
        # The bill keeps its single-click editing: an amount box that needs a
        # double-click reads as read-only, which is the confusion this fixes.
        self.bill_table.setEditTriggers(
            QAbstractItemView.NoEditTriggers if locked else self.BILL_TRIGGERS)
        for button in self.edit_buttons:
            button.setEnabled(not locked)

    def request_edit_access(self) -> bool:
        """Ask for the password and unlock the form if it is correct."""
        from .password_dialog import request_unlock

        if not self.read_only:
            return True
        if request_unlock(self, "edit this saved report"):
            self.set_read_only(False)
            self.notify.emit(
                "Report unlocked - saving now overwrites the stored record.",
                "warning")
            return True
        self.notify.emit("Report stays read-only.", "info")
        return False

    # ----------------------------------------------------------- form state
    def is_dirty(self) -> bool:
        """True if the form holds anything the operator typed.

        The patient ID and the timestamps are generated, so they never count as
        user input - otherwise a freshly cleared form would look dirty."""
        typed = (self.f_name, self.f_age, self.f_phone, self.f_ref,
                 self.f_remarks, self.f_deposit)
        return any(w.text().strip() for w in typed) or self.table.rowCount() > 0

    def clear_clicked(self):
        """Clear is destructive to unsaved typing, so confirm before wiping it."""
        if self.is_dirty():
            confirm = QMessageBox.question(
                self, "Clear form",
                "Clear the form and start a new report?\n\n"
                "Anything not saved yet will be lost.",
                QMessageBox.Yes | QMessageBox.No, QMessageBox.No,
            )
            if confirm != QMessageBox.Yes:
                return
        self.new_report()
        self.notify.emit("Form cleared - ready for a new report.", "info")

    # ------------------------------------------------------------ table logic
    def _append_row(self, row: TestRow):
        self._loading = True
        r = self.table.rowCount()
        self.table.insertRow(r)
        for col, value in enumerate((row.name, row.result, row.unit, row.ref)):
            item = QTableWidgetItem(value)
            if col == 0:
                item.setData(Qt.UserRole, row.panel)
                item.setData(HEADING_ROLE, row.kind)
            self.table.setItem(r, col, item)

        if row.is_heading():
            self._style_heading(r)
        self._loading = False
        self._restyle_row(r)
        self._update_row_count()

    def _style_heading(self, r: int):
        """A sub-heading is a band across the grid: no result, unit or range."""
        head = self.table.item(r, 0)
        font = QFont()
        font.setBold(True)
        head.setFont(font)
        head.setForeground(QBrush(QColor(ACCENT_DARK)))
        head.setBackground(QBrush(QColor(SURFACE_ALT)))
        for col in (1, 2, 3):
            cell = self.table.item(r, col)
            cell.setText("")
            cell.setFlags(Qt.ItemIsEnabled)
            cell.setBackground(QBrush(QColor(SURFACE_ALT)))

    def is_heading_row(self, r: int) -> bool:
        item = self.table.item(r, 0)
        return item is not None and item.data(HEADING_ROLE) == "heading"

    def _update_row_count(self):
        n = sum(1 for r in range(self.table.rowCount()) if not self.is_heading_row(r))
        self.row_count_label.setText(f"{n} test{'s' if n != 1 else ''}" if n else "")

    def _delete_row(self):
        rows = sorted({i.row() for i in self.table.selectedIndexes()}, reverse=True)
        if not rows:
            self.notify.emit("Select a cell in the row you want to delete.", "warning")
            return
        for r in rows:
            self.table.removeRow(r)
        self._update_row_count()
        self._sync_bill_items()

    def _add_blank_row(self):
        self._append_row(TestRow("Investigations", "", "", "", ""))
        self._sync_bill_items()

    def _item_changed(self, item):
        if self._loading or self._styling:
            return
        self._restyle_row(item.row())
        if item.column() == 0:
            # Naming a hand-added row is what makes it billable, so the bill has
            # to follow the test name as well as the panel ticks.
            self._sync_bill_items()

    def _cell_problem(self, r: int, col: int):
        """The validation message for one grid cell, or None."""
        item = self.table.item(r, col)
        text = item.text() if item else ""
        if col == 0:
            return V.check_test_name(text, "test name")
        if col == 1:
            return V.check_result_value(text)
        if col == 2:
            return V.check_unit(text)
        if col == 3:
            return V.check_reference(text)
        return None

    def _mark_cell(self, r: int, col: int):
        """Mark an invalid cell in red.

        Not a background tint: a Qt stylesheet on QTableWidget::item takes over
        item rendering and ignores the model's background brush, so the tint is
        simply never drawn. Foreground colour still gets through."""
        item = self.table.item(r, col)
        if item is None:
            return
        problem = self._cell_problem(r, col)
        if not problem and col == 1:
            # The result column already carries its H / L styling; resetting it
            # here would wipe the red on an out-of-range value.
            return None

        font = QFont()
        font.setBold(bool(problem))
        font.setItalic(bool(problem))
        item.setFont(font)
        item.setForeground(QBrush(QColor(DANGER if problem else "#000000")))
        item.setToolTip(problem or "")
        return problem

    def _restyle_row(self, r: int):
        """Re-entrant by nature: setting a font or colour on an item emits
        itemChanged, which lands back here. The guard stops the H/L styling and
        the invalid-cell marking from overwriting each other forever."""
        if self.is_heading_row(r) or self._styling:
            return
        self._styling = True
        try:
            self._restyle_row_now(r)
        finally:
            self._styling = False

    def _restyle_row_now(self, r: int):
        result_item = self.table.item(r, 1)
        ref_item = self.table.item(r, 3)
        if result_item is None or ref_item is None:
            return

        flag = flag_for(result_item.text(), ref_item.text())
        font = QFont()
        font.setBold(bool(flag))
        result_item.setFont(font)
        result_item.setForeground(QBrush(QColor("#c00000" if flag else "#000000")))
        result_item.setToolTip({"H": "Above reference range",
                                "L": "Below reference range"}.get(flag, ""))

        # last, so an invalid cell always shows as invalid rather than as a flag
        for col in (0, 1, 2, 3):
            self._mark_cell(r, col)

    def _panel_toggled(self, panel: str, checked: bool):
        if checked:
            for row in templates.rows_for(panel):
                self._append_row(TestRow(
                    panel=panel, name=row["name"], result="", unit=row.get("unit", ""),
                    ref=templates.ref_for(row, self.f_sex.currentText()),
                    kind=row.get("kind", "test")))
        else:
            for r in range(self.table.rowCount() - 1, -1, -1):
                item = self.table.item(r, 0)
                if item is not None and item.data(Qt.UserRole) == panel:
                    self.table.removeRow(r)
            self._update_row_count()
        self._sync_bill_items()

    def _sex_changed(self):
        """Re-resolve sex-specific reference ranges when the patient's sex changes."""
        sex = self.f_sex.currentText()
        self._loading = True
        for r in range(self.table.rowCount()):
            name_item = self.table.item(r, 0)
            if name_item is None:
                continue
            panel = name_item.data(Qt.UserRole)
            for row in templates.rows_for(panel or ""):
                if row["name"] == name_item.text() and row.get("kind") != "heading":
                    self.table.item(r, 3).setText(templates.ref_for(row, sex))
                    break
        self._loading = False
        for r in range(self.table.rowCount()):
            self._restyle_row(r)

    # --------------------------------------------------------------- report io
    def _collect_rows(self):
        """The result rows as they stand in the grid. Shared by `collect` and by
        the billing sync, so the bill is always derived from exactly the rows
        that will be saved and printed."""
        rows = []
        for r in range(self.table.rowCount()):
            name = self.table.item(r, 0)
            if name is None or not name.text().strip():
                continue
            heading = self.is_heading_row(r)
            rows.append(TestRow(
                panel=name.data(Qt.UserRole) or "Investigations",
                name=name.text().strip(),
                result="" if heading else
                (self.table.item(r, 1).text() if self.table.item(r, 1) else "").strip(),
                unit="" if heading else
                (self.table.item(r, 2).text() if self.table.item(r, 2) else "").strip(),
                ref="" if heading else
                (self.table.item(r, 3).text() if self.table.item(r, 3) else "").strip(),
                kind="heading" if heading else "test",
            ))
        return rows

    def collect(self) -> Report:
        return Report(
            id=self.current_id,
            report_no=self.current_report_no,
            patient_name=self.f_name.text().strip(),
            age=self.f_age.text().strip(),
            age_unit=self.age_unit_code(),
            sex=self.f_sex.currentText(),
            patient_id=self.f_pid.text().strip(),
            phone=V.normalise_phone(self.f_phone.text()),
            referred_by=self.f_ref.text().strip(),
            sample_type=self.f_sample.currentText().strip(),
            collected_on=self.f_collected.dateTime().toString(QT_DATE_FMT),
            reported_on=self.f_reported.dateTime().toString(QT_DATE_FMT),
            remarks=self.f_remarks.text().strip(),
            panels=[n for n, cb in self.panel_boxes.items() if cb.isChecked()],
            rows=self._collect_rows(),
            billing=self._collect_billing(),
            created_at=self.current_created_at,
        )

    def new_report(self):
        self._loading = True
        self.current_id = ""
        self.current_report_no = ""
        self.current_created_at = ""
        for name, cb in self.panel_boxes.items():
            cb.blockSignals(True)
            cb.setChecked(False)
            cb.blockSignals(False)
            self._style_chip(name, False)
        self.table.setRowCount(0)
        self._update_row_count()
        for field in (self.f_name, self.f_age, self.f_phone, self.f_ref,
                      self.f_remarks):
            field.clear()
        self.f_pid.setText(storage.peek_patient_id())
        self.f_sex.setCurrentIndex(0)
        self.f_age_unit.setCurrentIndex(0)
        self.f_sample.setCurrentIndex(0)
        now = QDateTime.currentDateTime()
        self.f_collected.setDateTime(now)
        self.f_reported.setDateTime(now)
        self.l_report_no.setText(storage.peek_report_no())
        self.f_bill_no.setText(storage.peek_bill_no())
        self.f_bill_date.setDateTime(QDateTime.currentDateTime())
        self.f_bill_type.setCurrentIndex(0)
        # Typed once on the Laboratory Profile, not once per bill.
        self.f_billed_by.setText(storage.load_profile().billed_by)
        self.f_deposit.clear()
        self._fill_bill_table([])
        self._update_bill_totals()
        self.set_read_only(False)
        self._loading = False
        self.f_name.setFocus()

    def forget_if_deleted(self, deleted_ids) -> bool:
        """If the report currently open in the form was deleted from History,
        the form must not keep showing it - saving again would resurrect it."""
        if self.current_id and self.current_id in set(deleted_ids):
            self.new_report()
            return True
        return False

    def load_report(self, report: Report, as_copy: bool = False):
        self.new_report()
        self._loading = True
        if not as_copy:
            self.current_id = report.id
            self.current_report_no = report.report_no
            self.current_created_at = report.created_at
            self.l_report_no.setText(report.report_no)
        self.f_name.setText(report.patient_name)
        self.f_age.setText(report.age)
        self.set_age_unit(report.age_unit or "Y")
        self.f_sex.blockSignals(True)
        self.f_sex.setCurrentText(report.sex or "M")
        self.f_sex.blockSignals(False)
        self.f_pid.setText(report.patient_id or storage.peek_patient_id())
        self.f_phone.setText(report.phone)
        self.f_ref.setText(report.referred_by)
        self.f_sample.setCurrentText(report.sample_type)
        if not as_copy:
            self._set_date(self.f_collected, report.collected_on)
            self._set_date(self.f_reported, report.reported_on)
            self.f_remarks.setText(report.remarks)
            # A duplicate is a fresh visit: it keeps the patient and the panels
            # but not the previous bill, so its own number, date and amounts are
            # left to be filled in - the same reason its results start blank.
            self._load_billing(report.billing)
        for name, cb in self.panel_boxes.items():
            cb.blockSignals(True)
            cb.setChecked(name in report.panels)
            cb.blockSignals(False)
            self._style_chip(name, name in report.panels)
        self.table.setRowCount(0)
        self._loading = False
        self.set_read_only(
            not as_copy,
            f"Viewing saved report {report.report_no} for {report.patient_name}. "
            "Saved reports open read-only so a finished record is not changed "
            "by accident.")
        for row in report.rows:
            self._append_row(TestRow(row.panel, row.name, "" if as_copy else row.result,
                                     row.unit, row.ref, row.kind))
        # Reconcile once at the end rather than per row: a saved bill already
        # matches its rows, so this is a no-op for a well-formed report and a
        # repair for one that was hand-edited on disk.
        self._sync_bill_items()

    # ----------------------------------------------------------------- actions
    def _mark_age(self):
        """Tint the age box while it holds an implausible value."""
        bad = bool(self.f_age.text().strip()) and bool(
            V.check_age(self.f_age.text(), self.age_unit_code()))
        self.f_age.setStyleSheet(
            "border: 1px solid #c0392b; background: #fdf3f2;" if bad else "")

    def _validate(self) -> bool:
        problem = V.first_error(
            V.check_person_name(self.f_name.text(), "patient name"),
            V.check_age(self.f_age.text(), self.age_unit_code()),
            V.check_optional_name(self.f_ref.text(), "referring doctor's name"),
            V.check_phone(self.f_phone.text(), "patient's phone number"),
        )
        if problem:
            self.notify.emit(problem, "warning")
            if "age" in problem.lower():
                self.f_age.setFocus()
            elif "phone" in problem.lower():
                self.f_phone.setFocus()
            elif "doctor" in problem.lower():
                self.f_ref.setFocus()
            else:
                self.f_name.setFocus()
            return False

        if self.table.rowCount() == 0:
            self.notify.emit("Select at least one panel, or add a test row.", "warning")
            return False

        for r in range(self.table.rowCount()):
            if self.is_heading_row(r):
                if not self.table.item(r, 0).text().strip():
                    self.notify.emit(f"Row {r + 1}: give the sub-heading a name.",
                                     "warning")
                    self.table.setCurrentCell(r, 0)
                    return False
                continue
            for col, field in ((0, "test"), (1, "result"), (2, "unit"),
                               (3, "reference range")):
                message = self._cell_problem(r, col)
                if message:
                    self.notify.emit(f"Row {r + 1} ({field}): {message}", "warning")
                    self.table.setCurrentCell(r, col)
                    return False

        return self._validate_billing()

    def _validate_billing(self) -> bool:
        """Billing is optional, so a blank bill is valid. What is not valid is a
        figure that cannot be added up, or a deposit larger than the bill it is
        being paid against - refunds are out of scope, so a negative balance can
        only be a slipped keystroke."""
        problem = V.first_error(
            V.check_bill_no(self.f_bill_no.text()),
            V.check_optional_name(self.f_billed_by.text(), "billed-by name"),
        )
        if problem:
            self.notify.emit(problem, "warning")
            (self.f_billed_by if "billed-by" in problem
             else self.f_bill_no).setFocus()
            return False

        for row in range(self.bill_table.rowCount()):
            service = self.bill_table.item(row, 0)
            amount = self.bill_table.item(row, 1)
            label = f"amount for {service.text()}" if service else "amount"
            message = V.check_amount(amount.text() if amount else "", label)
            if message:
                self.notify.emit(message, "warning")
                self.bill_table.setCurrentCell(row, 1)
                return False

        problem = V.check_amount(self.f_deposit.text(), "net deposit")
        if problem:
            self.notify.emit(problem, "warning")
            self.f_deposit.setFocus()
            return False

        figures = billing.summary(self._collect_billing())
        if figures["balance"] < 0:
            self.notify.emit(
                f"The net deposit ({billing.format_money(figures['net_deposit'])}) "
                f"is more than the net payable amount "
                f"({billing.format_money(figures['net_payable'])}). "
                "Check the amounts before saving.", "warning")
            self.f_deposit.setFocus()
            return False
        return True

    def save(self) -> bool:
        if self.read_only:
            self.notify.emit(
                "This saved report is read-only. Use Unlock to Edit to change it.",
                "warning")
            return False
        if not self._validate():
            return False
        report = storage.save_report(self.collect())
        self.current_id = report.id
        self.current_report_no = report.report_no
        self.current_created_at = report.created_at
        self.l_report_no.setText(report.report_no)
        self.f_pid.setText(report.patient_id)
        self.f_phone.setText(report.phone)
        # storage allocates the bill number and date when they were left blank,
        # so show what was actually stored rather than what was on screen.
        self._load_billing(report.billing)
        self.saved.emit()
        if storage.should_ask_for_backup():
            self._ask_for_drive()
        # One toast, not two: a backup problem must not be painted over by
        # the success message that would otherwise follow it.
        saved = (f"Report {report.report_no} saved for {report.patient_name} "
                 f"({report.patient_id}).")
        problem = self._backup(report)
        if problem:
            self.notify.emit(saved + " " + problem, "warning")
        elif storage.backup_dir():
            self.notify.emit(saved + " Copied to the backup folder.", "success")
        else:
            self.notify.emit(saved, "success")
        return True

    # Swappable so a headless run (tests, scripts) never blocks on the dialog.
    drive_prompt = staticmethod(ask_for_drive)

    def _ask_for_drive(self):
        problem = apply_answer(self.drive_prompt(self))
        if problem:
            self.notify.emit(problem, "warning")

    def _backup(self, report) -> str:
        """Copy the saved report to the backup folder as data plus a PDF.

        The PDF is what the lab actually wants in Drive - something they can
        open on a phone and send to a patient - and it is rendered here rather
        than in storage because only the UI layer can reach the printer stack.
        Returns a one-line problem to show, or "" when all went well (or
        backup is off). Never raises: the report is already safe on disk."""
        if not storage.backup_dir():
            return ""
        month = storage.backup_copy(report)
        if not month:
            return ("The backup folder could not be written - check it in "
                    "Laboratory Profile.")
        pdf = os.path.join(month, storage.backup_name(report) + ".pdf")
        try:
            printing.export_pdf(build(report, storage.load_profile()), pdf)
        except OSError:
            pass
        # QPrinter reports nothing when it cannot write, so look for the file.
        if not os.path.isfile(pdf):
            return "Backed up the data, but the PDF copy could not be written."
        return ""

    def _html(self) -> str:
        return build(self.collect(), storage.load_profile())

    def preview(self):
        if self._validate():
            printing.preview_report(self._html(), self)

    def print_report(self):
        """Save before printing, so nothing leaves the app unrecorded.

        A locked report is already saved, so it prints straight away - printing
        does not change the record, and refusing a reprint would just push the
        operator to History for something they are already looking at."""
        if self.read_only:
            if not self._validate():
                return
            if printing.print_report(self._html(), self):
                self.notify.emit(
                    f"Report {self.current_report_no} sent to the printer.", "success")
            return
        if not self.save():
            return
        if printing.print_report(self._html(), self):
            self.notify.emit(f"Report {self.current_report_no} sent to the printer.", "success")
        else:
            self.notify.emit(
                f"Printing cancelled. Report {self.current_report_no} is saved in History.",
                "warning")

    def export_pdf(self):
        if not self._validate():
            return
        default = f"{self.f_name.text().strip() or 'report'}.pdf".replace(" ", "_")
        path, _ = QFileDialog.getSaveFileName(self, "Export PDF", default, "PDF (*.pdf)")
        if path:
            printing.export_pdf(self._html(), path)
            QMessageBox.information(self, "Exported", f"Saved to:\n{path}")
