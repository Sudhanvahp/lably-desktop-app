        path, _ = QFileDialog.getSaveFileName(self, "Export Bill PDF", default,
                                              "PDF (*.pdf)")
        if path:
            printing.export_pdf(self._bill_html(), path, printing.BILL_PAGE)
            QMessageBox.information(self, "Exported", f"Saved to:\n{path}")

