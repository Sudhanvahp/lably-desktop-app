    @staticmethod
    def _described(widget, help_key: str, trailing: str = "") -> QWidget:
        """A field with its one-line description underneath.

        The description sits under the control rather than in a tooltip so it
        is readable without hunting for it - this app is used by staff who may
        never have been trained on it."""
        wrapper = QWidget()
        wrapper.setObjectName("Bare")
        column = QVBoxLayout(wrapper)
        column.setContentsMargins(0, 0, 0, 0)
        column.setSpacing(1)

        if trailing:
            top = QHBoxLayout()
            top.setContentsMargins(0, 0, 0, 0)
            top.setSpacing(S2)
            if isinstance(widget, QWidget):
                top.addWidget(widget)
            else:
                top.addLayout(widget)
            note = QLabel(trailing)
            note.setObjectName("Hint")
            top.addWidget(note)
            top.addStretch(1)
            column.addLayout(top)
        elif isinstance(widget, QWidget):
            column.addWidget(widget)
        else:
            column.addLayout(widget)

        description = QLabel(FIELD_HELP.get(help_key, ""))
        description.setObjectName("FieldHelp")
        description.setWordWrap(True)
        column.addWidget(description)
        return wrapper

