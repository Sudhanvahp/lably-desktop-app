    def _fill_bill_table(self, items):
        self._bill_loading = True
        try:
            self.bill_table.setRowCount(0)
            for i, item in enumerate(items):
                self.bill_table.insertRow(i)
                service = QTableWidgetItem(item.service)
                # The service name is not typed here - it is whatever panel the
                # operator ticked, and editing it would only let the bill drift
                # away from the results it is charging for.
                service.setFlags(Qt.ItemIsEnabled | Qt.ItemIsSelectable)
                service.setToolTip("Comes from the panels selected above.")
                self.bill_table.setItem(i, 0, service)
                amount = QTableWidgetItem(item.amount)
                amount.setTextAlignment(Qt.AlignRight | Qt.AlignVCenter)
                self.bill_table.setItem(i, 1, amount)
        finally:
            self._bill_loading = False
        self.bill_empty.setVisible(not items)
        self.bill_table.setVisible(bool(items))
        # A bill has a handful of lines, so the table is sized to its contents
        # rather than left as a fixed box with an empty half. Past the cap it
        # scrolls, which only happens on a report carrying a dozen panels.
        rows = self.bill_table.horizontalHeader().height() + 2
        rows += sum(self.bill_table.rowHeight(r) for r in range(len(items)))
        self.bill_table.setFixedHeight(min(rows, 240))

    def _sync_bill_items(self):
        """Re-derive the bill lines from the results grid, keeping typed amounts.

        Called whenever the selected work changes - a panel ticked or unticked, a
        row added, deleted or renamed - so the bill can never be charging for a
        panel that is no longer on the report.
        """
        items = billing.sync_items(self._collect_billing(), self._collect_rows())
        self._fill_bill_table(items)
        self._update_bill_totals()

    def _bill_item_changed(self, item):
        if not self._bill_loading:
            self._update_bill_totals()

    def _mark_amount_cell(self, row: int) -> bool:
        """Red-italic an unusable amount, the same way the results grid marks a
        bad cell. Returns True when the cell is fine."""
        cell = self.bill_table.item(row, 1)
        if cell is None:
            return True
        problem = V.check_amount(cell.text(), "amount")
        font = QFont()
        font.setBold(bool(problem))
        font.setItalic(bool(problem))
        cell.setFont(font)
        cell.setForeground(QBrush(QColor(DANGER if problem else "#000000")))
        cell.setToolTip(problem or "")
        return not problem

    def _update_bill_totals(self):
        """Recompute and repaint the four figures. Invalid amounts count as
        nothing rather than freezing the total, so the number on screen always
        matches the amounts that are actually usable."""
        if self._bill_loading:
            return
        self._bill_loading = True
        try:
            for row in range(self.bill_table.rowCount()):
                self._mark_amount_cell(row)
        finally:
            self._bill_loading = False

        figures = billing.summary(self._collect_billing())
        self.l_total.setText(billing.format_amount(figures["total_billed"]))
        self.l_payable.setText(billing.format_amount(figures["net_payable"]))
        self.l_balance.setText(billing.format_amount(figures["balance"]))
        # Amber-free: owed is crimson, settled is green. Same repolish dance as
        # the panel chips, because an object name change alone does not restyle.
        due = figures["balance"] > 0
        self.l_balance.setObjectName("BillBalance" if due else "BillBalanceClear")
        self.l_balance.style().unpolish(self.l_balance)
        self.l_balance.style().polish(self.l_balance)

    def _load_billing(self, bill: Billing):
        """Put a stored bill back on the form.

        The first build stored the day alone, so that format is tried too; a date
        the app still cannot read falls back to now rather than throwing."""
        self.f_bill_no.setText(bill.bill_no or storage.peek_bill_no())
        when = QDateTime.fromString(bill.bill_date or "", billing.BILL_QT_DATE_FMT)
        if not when.isValid():
            legacy = QDate.fromString(bill.bill_date or "", "dd-MM-yyyy")
            when = legacy.startOfDay() if legacy.isValid() else QDateTime()
        self.f_bill_date.setDateTime(
            when if when.isValid() else QDateTime.currentDateTime())
        self.f_bill_type.setCurrentText(bill.bill_type or billing.DEFAULT_BILL_TYPE)
        self.f_billed_by.setText(bill.billed_by or storage.load_profile().billed_by)
        self.f_deposit.setText(bill.net_deposit)
        self._fill_bill_table(bill.items)
        self._update_bill_totals()

    def _collect_billing(self) -> Billing:
        items = []
        for row in range(self.bill_table.rowCount()):
            service = self.bill_table.item(row, 0)
            amount = self.bill_table.item(row, 1)
            if service is None or not service.text().strip():
                continue
            items.append(BillItem(
                service=service.text().strip(),
                amount=(amount.text().strip() if amount else ""),
            ))
        return Billing(
            bill_no=self.f_bill_no.text().strip(),
            bill_date=self.f_bill_date.dateTime().toString(billing.BILL_QT_DATE_FMT),
            bill_type=self.f_bill_type.currentText(),
            billed_by=self.f_billed_by.text().strip(),
            net_deposit=self.f_deposit.text().strip(),
            items=items,
        )

