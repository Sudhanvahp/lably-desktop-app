    @staticmethod
    def _bill_date_field() -> QDateTimeEdit:
        """Down to the second, because that is what the bill prints and because
        two bills for one patient on one morning have to be tellable apart."""
        field = QDateTimeEdit()
        field.setDisplayFormat("dd-MM-yyyy  hh:mm:ss AP")
        field.setCalendarPopup(True)
        field.setDateTime(QDateTime.currentDateTime())
        field.setMinimumDate(QDate(1900, 1, 1))
        field.setMaximumDateTime(QDateTime.currentDateTime().addYears(1))
