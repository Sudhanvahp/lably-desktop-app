    def _build_panel_box(self) -> Card:
        box = Card("Test Panels", "tick a panel to load its tests")
        self.panel_grid = QGridLayout()
        self.panel_grid.setHorizontalSpacing(S2 + 2)
        self.panel_grid.setVerticalSpacing(6)
        self.panel_boxes = {}
        self.panel_chips = {}
        box.add(self.panel_grid)
        self._fill_panel_chips()
        return box

    def _fill_panel_chips(self):
        """Rebuild the chip row from the saved templates, so a panel created or
        renamed in the Test Templates page shows up here without a restart."""
        grid = self.panel_grid
        while grid.count():
            item = grid.takeAt(0)
            if item.widget():
                item.widget().deleteLater()
        self.panel_boxes.clear()
        self.panel_chips.clear()

        names = templates.panel_names()
        for i, name in enumerate(names):
            chip = QFrame()
            chip.setObjectName("PanelChip")
            chip.setCursor(Qt.PointingHandCursor)
            inner = QHBoxLayout(chip)
            inner.setContentsMargins(S2 + 2, 0, S3, 0)

            cb = QCheckBox(name.split("(")[0].strip())
            cb.setToolTip(f"{name} - tick to load its tests, untick to remove them")
            cb.toggled.connect(lambda checked, n=name: self._panel_toggled(n, checked))
            cb.toggled.connect(lambda checked, n=name: self._style_chip(n, checked))
            inner.addWidget(cb)
            inner.addStretch(1)

            self.panel_boxes[name] = cb
            self.panel_chips[name] = chip
            grid.addWidget(chip, i // 3, i % 3)

        for col in range(3):
            grid.setColumnStretch(col, 1)

    def refresh_panels(self):
        """Called when the templates change. Panels still loaded in the grid are
        left alone - the operator's typed results must survive an edit."""
        checked = {name for name, cb in self.panel_boxes.items() if cb.isChecked()}
        self._fill_panel_chips()
        for name in checked:
            cb = self.panel_boxes.get(name)
            if cb is not None:
                cb.blockSignals(True)
                cb.setChecked(True)
                cb.blockSignals(False)
                self._style_chip(name, True)

    def _style_chip(self, panel: str, checked: bool):
        """Light the whole chip, not just the tick, so a selected panel reads
        at a glance from across the room."""
        chip = self.panel_chips.get(panel)
        if chip is None:
            return
        chip.setObjectName("PanelChipOn" if checked else "PanelChip")
        chip.style().unpolish(chip)
        chip.style().polish(chip)

