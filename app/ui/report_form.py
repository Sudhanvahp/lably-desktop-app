    def _bill_ready(self) -> bool:
        """A bill with no figures on it is not a bill. Checked before every bill
        action so the operator is told why, instead of being handed a blank."""
        if not self._validate():
            return False
        if not billing.has_content(self._collect_billing()):
            self.notify.emit(
                "Enter an amount against at least one service before printing "
                "the bill.", "warning")
            return False
        return True

